package de.codeflowwizardry.carledger.notification.push;

import java.net.URI;
import java.nio.charset.StandardCharsets;
import java.security.GeneralSecurityException;
import java.security.KeyPair;
import java.security.Signature;
import java.security.interfaces.ECPublicKey;
import java.time.Duration;
import java.time.Instant;
import java.util.Arrays;
import java.util.Base64;

/**
 * The key pair of the server (VAPID, RFC 8292): the browsers subscribe with
 * its public key, the push services accept only messages signed with its
 * private key. It must stay the same, a new key invalidates all subscriptions.
 */
public final class VapidKeys
{
	private static final Base64.Encoder BASE64URL = Base64.getUrlEncoder().withoutPadding();

	private final KeyPair keys;

	VapidKeys(KeyPair keys)
	{
		this.keys = keys;
	}

	/**
	 * @param pem
	 *            the private key as "EC PRIVATE KEY" (SEC1, RFC 5915) with its
	 *            public key, as generated by Helm (genPrivateKey "ecdsa") or
	 *            openssl ecparam -name prime256v1 -genkey -noout
	 */
	public static VapidKeys fromPem(String pem) throws GeneralSecurityException
	{
		String base64 = pem.replaceAll("-----[A-Z ]+-----", "").replaceAll("\\s", "");
		byte[] der = Base64.getDecoder().decode(base64);

		// SEQUENCE { INTEGER 1, OCTET STRING d, [0] parameters, [1] BIT STRING public
		// key }
		Der sequence = Der.read(der, 0).expect(0x30);
		Der version = Der.read(der, sequence.contentStart).expect(0x02);
		Der privateKey = Der.read(der, version.end).expect(0x04);
		byte[] d = privateKey.content(der);
		byte[] publicKey = null;
		int position = privateKey.end;
		while (position < sequence.end)
		{
			Der field = Der.read(der, position);
			if (field.tag == 0xa1)
			{
				Der bits = Der.read(der, field.contentStart).expect(0x03);
				// the first byte counts the unused bits
				publicKey = Arrays.copyOfRange(der, bits.contentStart + 1, bits.end);
			}
			position = field.end;
		}
		if (d.length != 32 || publicKey == null)
		{
			throw new GeneralSecurityException("Not a P-256 private key with its public key (EC PRIVATE KEY)");
		}
		return new VapidKeys(new KeyPair(WebPushCrypto.publicKey(publicKey), WebPushCrypto.privateKey(d)));
	}

	public static VapidKeys generate()
	{
		return new VapidKeys(WebPushCrypto.generateKeyPair());
	}

	/**
	 * @return the public key for the subscriptions of the browsers, base64url
	 */
	public String publicKey()
	{
		return BASE64URL.encodeToString(WebPushCrypto.raw((ECPublicKey) keys.getPublic()));
	}

	/**
	 * @param subject
	 *            contact of the operator, mailto: or https: (Apple rejects
	 *            messages without one)
	 * @return the header Authorization for a message to the endpoint, valid for
	 *         12 hours
	 */
	public String authorization(URI endpoint, String subject, Instant now)
	{
		String audience = endpoint.getScheme() + "://" + endpoint.getRawAuthority();
		String header = BASE64URL
				.encodeToString("{\"typ\":\"JWT\",\"alg\":\"ES256\"}".getBytes(StandardCharsets.UTF_8));
		String claims = BASE64URL.encodeToString(("{\"aud\":\"" + json(audience) + "\",\"exp\":"
				+ now.plus(Duration.ofHours(12)).getEpochSecond() + ",\"sub\":\"" + json(subject) + "\"}")
				.getBytes(StandardCharsets.UTF_8));
		try
		{
			// ES256 of JWS: r and s with 32 bytes each, not DER
			Signature signature = Signature.getInstance("SHA256withECDSAinP1363Format");
			signature.initSign(keys.getPrivate());
			signature.update((header + "." + claims).getBytes(StandardCharsets.US_ASCII));
			String jwt = header + "." + claims + "." + BASE64URL.encodeToString(signature.sign());
			return "vapid t=" + jwt + ", k=" + publicKey();
		}
		catch (GeneralSecurityException e)
		{
			throw new IllegalStateException("The message cannot be signed", e);
		}
	}

	KeyPair keyPair()
	{
		return keys;
	}

	private static String json(String value)
	{
		return value.replace("\\", "\\\\").replace("\"", "\\\"");
	}

	/**
	 * A field of DER: tag, length and where it starts and ends
	 */
	private record Der(int tag, int contentStart, int end)
	{
		static Der read(byte[] der, int position) throws GeneralSecurityException
		{
			if (position + 2 > der.length)
			{
				throw new GeneralSecurityException("The key ends too early");
			}
			int tag = der[position] & 0xff;
			int length = der[position + 1] & 0xff;
			int start = position + 2;
			if (length > 0x80)
			{
				int bytes = length & 0x7f;
				length = 0;
				for (int i = 0; i < bytes; i++)
				{
					length = (length << 8) | (der[start + i] & 0xff);
				}
				start += bytes;
			}
			if (start + length > der.length)
			{
				throw new GeneralSecurityException("The key ends too early");
			}
			return new Der(tag, start, start + length);
		}

		Der expect(int expected) throws GeneralSecurityException
		{
			if (tag != expected)
			{
				throw new GeneralSecurityException("Unexpected field " + tag + " in the key");
			}
			return this;
		}

		byte[] content(byte[] der)
		{
			return Arrays.copyOfRange(der, contentStart, end);
		}
	}
}
