package de.codeflowwizardry.carledger;

import java.time.LocalDate;
import java.util.List;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import de.codeflowwizardry.carledger.data.RecurringBillEntity;
import de.codeflowwizardry.carledger.data.RecurringBillPaymentEntity;
import de.codeflowwizardry.carledger.data.repository.RecurringBillPaymentRepository;
import de.codeflowwizardry.carledger.data.repository.RecurringBillRepository;
import io.quarkus.narayana.jta.QuarkusTransaction;
import io.quarkus.scheduler.Scheduled;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.inject.Inject;

@ApplicationScoped
public class ScheduledPayments
{
	private final static Logger LOG = LoggerFactory.getLogger(ScheduledPayments.class);

	private final RecurringBillRepository recurringBillRepository;
	private final RecurringBillPaymentRepository recurringBillPaymentRepository;

	@Inject
	public ScheduledPayments(RecurringBillRepository recurringBillRepository,
			RecurringBillPaymentRepository recurringBillPaymentRepository)
	{
		this.recurringBillRepository = recurringBillRepository;
		this.recurringBillPaymentRepository = recurringBillPaymentRepository;
	}

	@Scheduled(cron = "0 0 1 * * ?")
	void generateDuePayments()
	{
		LocalDate today = LocalDate.now();
		List<Long> dueIds = QuarkusTransaction.requiringNew().call(() -> recurringBillRepository.listDueIds(today));

		for (Long id : dueIds)
		{
			try
			{
				// one transaction per bill, a failing bill must not roll back the payments of
				// the others
				QuarkusTransaction.requiringNew().run(() -> generateDuePayments(id, today));
			}
			catch (Exception e)
			{
				LOG.error("Could not generate payments for recurring bill {}", id, e);
			}
		}
	}

	/**
	 * Creates all payments due until the given day, so missed runs are caught up.
	 */
	private void generateDuePayments(long id, LocalDate today)
	{
		RecurringBillEntity bill = recurringBillRepository.findById(id);

		while (isDue(bill, today))
		{
			LocalDate dueDate = bill.getNextDueDate();

			if (recurringBillPaymentRepository.exists(bill, dueDate))
			{
				// A duplicate insert would violate the unique constraint
				LOG.warn("Payment for recurring bill {} on {} already exists, skipping", id, dueDate);
			} else
			{
				RecurringBillPaymentEntity payment = new RecurringBillPaymentEntity(bill);
				payment.setAmount(bill.getAmount());
				payment.setAutoGenerated(true);
				payment.setPaidDate(dueDate);
				payment.setDueDate(dueDate);
				recurringBillPaymentRepository.persist(payment);

				bill.setTotal(bill.getTotal().add(bill.getAmount()));
			}

			bill.advance();
		}
	}

	private static boolean isDue(RecurringBillEntity bill, LocalDate today)
	{
		return !bill.getNextDueDate().isAfter(today)
				&& (bill.getEndDate() == null || bill.getNextDueDate().isBefore(bill.getEndDate()));
	}
}
