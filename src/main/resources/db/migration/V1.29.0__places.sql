-- The places of a car its owner named, e.g. a fuel station it stops at often. The places themselves are found in the
-- stops of the GPS tracks; only the name is stored with its position, so it stays when the track points are deleted.
-- Part of the backup.
CREATE TABLE place
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pl_car_id     BIGINT           NOT NULL REFERENCES car (id) ON DELETE CASCADE,
    pl_lat        DOUBLE PRECISION NOT NULL,
    pl_lon        DOUBLE PRECISION NOT NULL,
    pl_name       VARCHAR(100)     NOT NULL,
    pl_created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE INDEX place_car_idx ON place (pl_car_id);
