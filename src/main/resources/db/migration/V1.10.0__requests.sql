-- Requests of users that an administrator decides, first: more cars

CREATE TABLE request
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rq_account_id   BIGINT      NOT NULL REFERENCES account (id) ON DELETE CASCADE,
    -- e.g. CAR_LIMIT, the payload depends on it
    rq_type         VARCHAR(30) NOT NULL,
    rq_payload      JSONB       NOT NULL,
    rq_reason       TEXT,
    -- OPEN, APPROVED or REJECTED
    rq_state        VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    rq_created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    rq_decided_at   TIMESTAMP WITH TIME ZONE,
    -- user name of the administrator or service account
    rq_decided_by   VARCHAR(255),
    rq_comment      TEXT,
    -- the user has seen the decision
    rq_outcome_seen BOOLEAN     NOT NULL DEFAULT FALSE
);

-- only one open request per user and type
CREATE UNIQUE INDEX request_open_unique ON request (rq_account_id, rq_type) WHERE rq_state = 'OPEN';
CREATE INDEX request_state_idx ON request (rq_state, rq_created_at);
