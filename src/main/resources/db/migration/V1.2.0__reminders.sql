-- Reminders of a car, due on a date and/or at an odometer reading

CREATE TABLE reminder
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rm_car_id          BIGINT                   NOT NULL REFERENCES car (id) ON DELETE CASCADE,
    rm_title           VARCHAR(100)             NOT NULL,
    rm_note            VARCHAR(500),
    rm_due_date        DATE,
    rm_due_odometer    INTEGER,
    -- repeating: the next due date/odometer is set from the completion
    rm_interval_months INTEGER,
    rm_interval_km     INTEGER,
    rm_created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),

    CONSTRAINT reminder_due CHECK (rm_due_date IS NOT NULL OR rm_due_odometer IS NOT NULL)
);

CREATE INDEX reminder_car_idx ON reminder (rm_car_id);
