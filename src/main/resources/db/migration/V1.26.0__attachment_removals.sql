-- The content of attachments outside the database (e.g. S3) isn't reached by the foreign keys: deleting an attachment,
-- its bill, modification, inspection, car or account, or moving its content to another storage, queues the old key
-- here, in the same transaction. A job of the app deletes the content and the row afterwards.
CREATE TABLE attachment_removal
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ar_storage     VARCHAR(20) NOT NULL,
    ar_storage_key TEXT        NOT NULL,
    ar_created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE OR REPLACE FUNCTION attachment_queue_removal() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    INSERT INTO attachment_removal (ar_storage, ar_storage_key) VALUES (OLD.a_storage, OLD.a_storage_key);
    RETURN NULL;
END;
$$;

-- also fired by the deletes of the foreign keys (ON DELETE CASCADE)
CREATE TRIGGER attachment_removal_on_delete
    AFTER DELETE
    ON attachment
    FOR EACH ROW
    WHEN (OLD.a_storage_key IS NOT NULL)
EXECUTE FUNCTION attachment_queue_removal();

CREATE TRIGGER attachment_removal_on_move
    AFTER UPDATE OF a_storage, a_storage_key
    ON attachment
    FOR EACH ROW
    WHEN (OLD.a_storage_key IS NOT NULL AND
          (OLD.a_storage, OLD.a_storage_key) IS DISTINCT FROM (NEW.a_storage, NEW.a_storage_key))
EXECUTE FUNCTION attachment_queue_removal();

-- the storages are compared when moving the files
CREATE INDEX attachment_storage_idx ON attachment (a_storage);
CREATE UNIQUE INDEX attachment_storage_key_idx ON attachment (a_storage_key) WHERE a_storage_key IS NOT NULL;
