-- Drives of the GPS tracks the owner dismissed as suggested trips. A drive found again that overlaps one isn't
-- suggested again. Not part of the backup.
CREATE TABLE trip_suggestion_dismissal
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts_car_id       BIGINT                   NOT NULL REFERENCES car (id) ON DELETE CASCADE,
    ts_started_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    ts_ended_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    ts_dismissed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),

    CONSTRAINT trip_suggestion_dismissal_range CHECK (ts_ended_at > ts_started_at)
);

CREATE INDEX trip_suggestion_dismissal_car_idx ON trip_suggestion_dismissal (ts_car_id, ts_ended_at);
