-- Notifications as Web Push: the browsers that subscribed, and the switch of the e-mails, now one channel of two

CREATE TABLE push_subscription
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ps_account_id BIGINT                   NOT NULL REFERENCES account (id) ON DELETE CASCADE,
    -- URL of the push service for the browser
    ps_endpoint   VARCHAR(2048)            NOT NULL UNIQUE,
    ps_p256dh     VARCHAR(100)             NOT NULL,
    ps_auth       VARCHAR(50)              NOT NULL,
    ps_created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE INDEX push_subscription_account_idx ON push_subscription (ps_account_id);

ALTER TABLE account ADD COLUMN notify_by_mail BOOLEAN NOT NULL DEFAULT TRUE;
