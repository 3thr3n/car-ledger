-- Files attached to a bill (receipts), later also to a car (picture). The
-- metadata is separate from the content, so lists never load the files.

CREATE TABLE attachment
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    a_car_id       BIGINT       NOT NULL REFERENCES car (id) ON DELETE CASCADE,
    a_bill_id      BIGINT REFERENCES bill (id) ON DELETE CASCADE,
    a_file_name    TEXT         NOT NULL,
    a_content_type VARCHAR(100) NOT NULL,
    a_size         BIGINT       NOT NULL,
    -- where the content is, e.g. DB; the key for storages outside the database
    a_storage      VARCHAR(20)  NOT NULL,
    a_storage_key  TEXT,
    a_created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX attachment_car_idx ON attachment (a_car_id);
CREATE INDEX attachment_bill_idx ON attachment (a_bill_id);

-- content of the attachments of the storage DB
CREATE TABLE attachment_content
(
    attachment_id BIGINT PRIMARY KEY REFERENCES attachment (id) ON DELETE CASCADE,
    ac_data       BYTEA NOT NULL
);
