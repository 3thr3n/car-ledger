-- Initial schema. Replaces all previous migrations, an existing database must be wiped before upgrading.

CREATE TABLE account
(
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  VARCHAR(255) NOT NULL UNIQUE,
    max_cars INTEGER      NOT NULL DEFAULT 1
);

CREATE TABLE car
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    c_user_id          BIGINT  NOT NULL REFERENCES account (id) ON DELETE CASCADE,
    c_name             TEXT    NOT NULL,
    c_manufacture_year INTEGER NOT NULL,
    c_odometer         INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX car_user_idx ON car (c_user_id);

CREATE TABLE bill
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    b_car_id     BIGINT         NOT NULL REFERENCES car (id) ON DELETE CASCADE,
    b_type       VARCHAR(50)    NOT NULL,
    b_date       DATE           NOT NULL,
    b_total      NUMERIC(38, 2) NOT NULL,
    b_vat_rate   INTEGER        NOT NULL,
    b_net_amount NUMERIC(38, 2) NOT NULL,
    b_ust_amount NUMERIC(38, 2) NOT NULL,

    -- the same amount on the same day is only a duplicate within one bill type
    CONSTRAINT bill_unique UNIQUE (b_car_id, b_type, b_date, b_total)
);

CREATE INDEX bill_car_date_idx ON bill (b_car_id, b_date);

CREATE TABLE bill_fuel
(
    bill_id           BIGINT PRIMARY KEY REFERENCES bill (id) ON DELETE CASCADE,
    f_unit            NUMERIC(38, 2) NOT NULL,
    f_price_per_unit  NUMERIC(38, 2) NOT NULL,
    f_distance        NUMERIC(38, 2),
    f_estimate        NUMERIC(38, 2),
    f_avg_consumption NUMERIC(38, 2),
    f_cost_per_km     NUMERIC(38, 2)
);

CREATE TABLE bill_maintenance
(
    bill_id       BIGINT PRIMARY KEY REFERENCES bill (id) ON DELETE CASCADE,
    m_odometer    INTEGER,
    m_description TEXT,
    m_workshop    TEXT,
    m_labor_cost  NUMERIC(38, 2),
    m_parts_cost  NUMERIC(38, 2)
);

CREATE TABLE bill_miscellaneous
(
    bill_id       BIGINT PRIMARY KEY REFERENCES bill (id) ON DELETE CASCADE,
    m_description TEXT
);

CREATE TABLE recurring_bill
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    r_car_id        BIGINT         NOT NULL REFERENCES car (id) ON DELETE CASCADE,
    r_name          TEXT           NOT NULL,
    r_description   TEXT,
    r_amount        NUMERIC(38, 2) NOT NULL,
    r_total         NUMERIC(38, 2) NOT NULL DEFAULT 0,
    r_category      VARCHAR(50)    NOT NULL,
    r_interval      VARCHAR(50)    NOT NULL,
    r_start_date    DATE           NOT NULL,
    r_next_due_date DATE           NOT NULL,
    r_end_date      DATE,

    CONSTRAINT recurring_bill_unique UNIQUE (r_car_id, r_category, r_amount, r_start_date, r_interval)
);

CREATE INDEX recurring_bill_next_due_idx ON recurring_bill (r_next_due_date);

CREATE TABLE recurring_bill_payment
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rp_recurring_bill_id BIGINT         NOT NULL REFERENCES recurring_bill (id) ON DELETE CASCADE,
    rp_due_date          DATE           NOT NULL,
    rp_paid_date         DATE           NOT NULL,
    rp_amount            NUMERIC(38, 2) NOT NULL,
    rp_auto_generated    BOOLEAN        NOT NULL,

    CONSTRAINT recurring_bill_payment_unique UNIQUE (rp_recurring_bill_id, rp_due_date)
);

CREATE INDEX recurring_bill_payment_due_idx ON recurring_bill_payment (rp_due_date);
