-- Modifications of a car with their approval (ABE, Teilegutachten, Einzelabnahme, ...). Removed ones stay as the
-- history of the car, the bill of the part or the installation is optional.
CREATE TABLE modification
(
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    md_car_id             BIGINT       NOT NULL REFERENCES car (id) ON DELETE CASCADE,
    md_bill_id            BIGINT REFERENCES bill (id) ON DELETE SET NULL,
    md_part               VARCHAR(100) NOT NULL,
    md_manufacturer       VARCHAR(100),
    md_approval_type      VARCHAR(20)  NOT NULL,
    md_approval_number    VARCHAR(50),
    md_conditions         VARCHAR(2000),
    md_inspection_date    DATE,
    md_testing_body       VARCHAR(100),
    md_registered         BOOLEAN      NOT NULL DEFAULT FALSE,
    md_installed_date     DATE,
    md_installed_odometer INTEGER,
    md_removed_date       DATE,
    md_removed_odometer   INTEGER,
    md_notes              VARCHAR(1000),

    CONSTRAINT modification_removed CHECK (md_removed_odometer IS NULL OR md_removed_date IS NOT NULL)
);

CREATE INDEX modification_car_idx ON modification (md_car_id);
CREATE INDEX modification_bill_idx ON modification (md_bill_id);
