-- Other accounts with access to a car, with their role; the owner stays c_user_id. An access counts only from its start
-- (if set) until before its end (if set), it ends by itself. Deleted with the car or the account.
CREATE TABLE car_access
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ca_car_id      BIGINT                   NOT NULL REFERENCES car (id) ON DELETE CASCADE,
    ca_account_id  BIGINT                   NOT NULL REFERENCES account (id) ON DELETE CASCADE,
    ca_role        VARCHAR(10)              NOT NULL,
    ca_valid_from  TIMESTAMP WITH TIME ZONE,
    ca_valid_until TIMESTAMP WITH TIME ZONE,
    -- the owner or an editor who gave it, kept when that account is deleted
    ca_created_by  BIGINT REFERENCES account (id) ON DELETE SET NULL,
    ca_created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),

    CONSTRAINT car_access_role CHECK (ca_role IN ('EDITOR', 'VIEWER', 'DRIVER')),
    CONSTRAINT car_access_period CHECK (ca_valid_until IS NULL OR ca_valid_from IS NULL OR ca_valid_until > ca_valid_from),
    -- one access per account and car, a new period changes it
    CONSTRAINT car_access_account UNIQUE (ca_car_id, ca_account_id)
);

CREATE INDEX car_access_account_idx ON car_access (ca_account_id);
