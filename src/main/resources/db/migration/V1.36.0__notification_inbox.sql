-- The inbox of an account (#485): every notification the server sends, also with mail and push off. The texts are
-- stored in the language of the account; the event and its values as well, to translate them in the app later.
-- Deleted after 90 days, read or not, and with the account.

CREATE TABLE notification
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nt_account_id BIGINT                   NOT NULL REFERENCES account (id) ON DELETE CASCADE,
    -- the template, e.g. car-access-invited
    nt_event      VARCHAR(40)              NOT NULL,
    -- what it is about, e.g. car-request-12: a decided request updates the notifications of the other administrators
    nt_tag        VARCHAR(100)             NOT NULL,
    nt_title      VARCHAR(300)             NOT NULL,
    nt_text       TEXT                     NOT NULL,
    -- the page of the app it opens
    nt_path       VARCHAR(200)             NOT NULL,
    nt_data       JSONB,
    nt_created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    nt_read_at    TIMESTAMP WITH TIME ZONE
);

CREATE INDEX notification_account_idx ON notification (nt_account_id, nt_created_at DESC);
CREATE INDEX notification_created_idx ON notification (nt_created_at);
