-- The technical inspections (HU with AU) of a car with their result and the next due month, their reports as
-- attachments. The reminder of the HU of a car follows the next due month of its latest inspection.
CREATE TABLE technical_inspection
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ti_car_id      BIGINT      NOT NULL REFERENCES car (id) ON DELETE CASCADE,
    ti_date        DATE        NOT NULL,
    ti_odometer    INTEGER,
    ti_testing_body VARCHAR(100),
    ti_result      VARCHAR(20) NOT NULL,
    ti_defects     VARCHAR(2000),
    -- the first day of the month
    ti_next_due    DATE
);

CREATE INDEX technical_inspection_car_idx ON technical_inspection (ti_car_id, ti_date);

ALTER TABLE attachment ADD COLUMN a_technical_inspection_id BIGINT REFERENCES technical_inspection (id) ON DELETE CASCADE;
CREATE INDEX attachment_technical_inspection_idx ON attachment (a_technical_inspection_id);
ALTER TABLE attachment DROP CONSTRAINT attachment_owner;
ALTER TABLE attachment ADD CONSTRAINT attachment_owner CHECK (num_nonnulls(a_bill_id, a_modification_id, a_technical_inspection_id) <= 1);

-- a reminder the app keeps, e.g. of the HU, one per car and kind
ALTER TABLE reminder ADD COLUMN rm_kind VARCHAR(30);
CREATE UNIQUE INDEX reminder_kind_idx ON reminder (rm_car_id, rm_kind) WHERE rm_kind IS NOT NULL;
