-- GPS trackers of a car (e.g. an ESP32) and the points of their tracks. A tracker authenticates with its own token,
-- only its SHA-256 is stored. A revoked tracker stays with its points.

CREATE TABLE device
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dv_car_id       BIGINT                   NOT NULL REFERENCES car (id) ON DELETE CASCADE,
    dv_name         VARCHAR(100)             NOT NULL,
    -- SHA-256 of the token, hex
    dv_token_hash   VARCHAR(64)              NOT NULL UNIQUE,
    dv_created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    -- updated at most once per minute
    dv_last_seen_at TIMESTAMP WITH TIME ZONE,
    dv_revoked_at   TIMESTAMP WITH TIME ZONE
);

CREATE INDEX device_car_idx ON device (dv_car_id);

-- The car is stored with every point, the queries of the tracks are per car and time. A point is sent again when the
-- tracker missed the answer, the unique key drops it then.
CREATE TABLE track_point
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tk_device_id BIGINT                   NOT NULL REFERENCES device (id) ON DELETE CASCADE,
    tk_car_id    BIGINT                   NOT NULL REFERENCES car (id) ON DELETE CASCADE,
    -- GPS time, UTC
    tk_ts        TIMESTAMP WITH TIME ZONE NOT NULL,
    tk_lat       DOUBLE PRECISION         NOT NULL,
    tk_lon       DOUBLE PRECISION         NOT NULL,
    -- km/h
    tk_speed     DOUBLE PRECISION,
    -- meters
    tk_alt       DOUBLE PRECISION,
    tk_hdop      DOUBLE PRECISION,

    CONSTRAINT track_point_device_ts UNIQUE (tk_device_id, tk_ts)
);

CREATE INDEX track_point_car_ts_idx ON track_point (tk_car_id, tk_ts);
